#!/usr/bin/env python3
"""Fig. 5: failed checks of the security assessment as a pgfplots stacked-row chart.

Reads the merged findings of Prowler and the audit script (JSON with a
"findings" list of {title, severity, status, ...}) and writes a plain
pgfplots axis: one row per area, stacked by severity, a dashed line between
account-wide hardening and settings of derived resources, row totals as
nodes near coords.

    python3 security_pgf.py --input MGridICSA-SecurityEval.json --output fig_security.tex
"""
import argparse
import json
from collections import Counter

ACCOUNT, DERIVED = "Account-wide hardening", "Settings of derived resources"

# rows top to bottom; the dashed line separates the two groups
ROWS = [
    (ACCOUNT, "Key mgmt. (KMS)"),
    (ACCOUNT, "Network placement"),
    (ACCOUNT, "Logging"),
    (ACCOUNT, "Backup \\& recovery"),
    (ACCOUNT, "Tagging"),
    (DERIVED, "Trust conditions"),
    (DERIVED, "Permission scope"),
    (DERIVED, "Dead-letter queues"),
    (DERIVED, "Device certificates"),
    (DERIVED, "Data retention"),
    (DERIVED, "Topic rule"),
    (DERIVED, "Bucket access"),
]

# check title prefix -> area
AREA_OF_CHECK = [
    ("Lambda function environment variables are encrypted", "Key mgmt. (KMS)"),
    ("CloudWatch log group is encrypted", "Key mgmt. (KMS)"),
    ("DynamoDB table is encrypted at rest", "Key mgmt. (KMS)"),
    ("S3 bucket has server-side encryption with AWS KMS", "Key mgmt. (KMS)"),
    ("Lambda function is deployed inside a VPC", "Network placement"),
    ("Lambda function Invoke API calls are recorded", "Logging"),
    ("S3 bucket has server access logging", "Logging"),
    ("S3 bucket has event notifications", "Logging"),
    ("DynamoDB table has deletion protection", "Backup \\& recovery"),
    ("DynamoDB table has point-in-time recovery", "Backup \\& recovery"),
    ("DynamoDB table is protected by a backup plan", "Backup \\& recovery"),
    ("S3 bucket has MFA Delete", "Backup \\& recovery"),
    ("S3 bucket has object versioning", "Backup \\& recovery"),
    ("S3 bucket has Object Lock", "Backup \\& recovery"),
    ("S3 bucket has cross-region replication", "Backup \\& recovery"),
    ("TwinMaker workspace has no tags", "Tagging"),
    ("IAM service role prevents cross-service confused deputy", "Trust conditions"),
    ("IAM role trust policy confines AWS service principals", "Trust conditions"),
    ("Lambda resource policy for iottwinmaker", "Trust conditions"),
    ("IAM inline policy does not allow privilege escalation", "Permission scope"),
    ("IoT policy allows wildcard actions", "Permission scope"),
    ("IoT policy applies to wildcard resources", "Permission scope"),
    ("Lambda function has a Dead Letter Queue", "Dead-letter queues"),
    ("IoT certificate is valid", "Device certificates"),
    ("S3 bucket has a lifecycle configuration", "Data retention"),
    ("IoT topic rule", "Topic rule"),
    ("S3 bucket policy denies requests over insecure transport", "Bucket access"),
    ("Workspace bucket CORS allows any origin", "Bucket access"),
]
SEVERITIES = ["High", "Medium", "Low"]
COLORS = {"High": "B2182B", "Medium": "EF8A62", "Low": "BABABA"}


def area_of(title):
    for prefix, area in AREA_OF_CHECK:
        if title.startswith(prefix):
            return area
    return None


def count(path):
    findings = json.load(open(path))["findings"]
    failed = [f for f in findings if f["status"] == "FAIL"]
    unmapped = sorted({f["title"] for f in failed if area_of(f["title"]) is None})
    if unmapped:
        raise SystemExit("unmapped failed checks:\n  " + "\n  ".join(unmapped))
    cnt = Counter((area_of(f["title"]), f["severity"]) for f in failed)
    sev = Counter(f["severity"] for f in failed)
    print(f"{len(findings)} checks, {len(failed)} failed, {dict(sev)}")
    for group in (ACCOUNT, DERIVED):
        print(f"  {group}: {sum(cnt[(a, s)] for g, a in ROWS if g == group for s in SEVERITIES)}")
    return cnt, sev


def tex(cnt, sev):
    used = [s for s in SEVERITIES if sev[s]]
    total = [sum(cnt[(a, s)] for s in used) for _, a in ROWS]
    n = len(ROWS)
    split = sum(g == ACCOUNT for g, _ in ROWS) - 0.5
    xmax = round(max(total) * 1.15)
    L = [r"% Generated by security_pgf.py. Requires \usetikzlibrary{decorations.pathreplacing}.",
         "".join(rf"\definecolor{{sev{s}}}{{HTML}}{{{COLORS[s]}}}" for s in used),
         r"\begin{tikzpicture}",
         r"\begin{axis}[",
         r"  xbar stacked, /pgf/bar width=5pt, y dir=reverse,",
         f"  scale only axis, width=0.35\\columnwidth, height={11 * n}pt,",
         f"  xmin=0, xmax={xmax}, ymin=-0.6, ymax={n - 0.4}, xlabel={{Failed checks}},",
         f"  ytick={{0,...,{n - 1}}}, yticklabels={{{','.join('{' + a + '}' for _, a in ROWS)}}},",
         f"  extra y ticks={{{split}}}, extra y tick labels={{}},",
         r"  extra y tick style={grid=major, major grid style={dashed, black!60}},",
         r"  axis x line*=bottom, axis y line*=left, ytick style={draw=none},",
         r"  xmajorgrids, grid style={gray!25},",
         r"  tick label style={font=\scriptsize}, label style={font=\scriptsize},",
         r"  legend style={font=\scriptsize, draw=none, fill=none, at={(1,0)}, anchor=south east, legend columns=1, cells={anchor=west}},",
         r"  area legend, clip=false,",
         r"]"]
    for s in used:
        pts = " ".join(f"({cnt[(a, s)]},{i})" for i, (_, a) in enumerate(ROWS))
        L.append(rf"\addplot[fill=sev{s}, draw=white, line width=0.3pt] coordinates {{{pts}}};")
        L.append(rf"\addlegendentry{{{s}}}")
    # Invisible last segment whose label is the row total. pgfplots drops labels
    # of increments that are exactly zero, so the segment gets a negligible width.
    pts = " ".join(f"(1e-4,{i}) [{t}]" for i, t in enumerate(total))
    L += [r"\addplot[draw=none, fill=none, forget plot, point meta=explicit symbolic,",
          r"  nodes near coords, nodes near coords style={font=\scriptsize, anchor=west, inner sep=1.5pt}]",
          f"  coordinates {{{pts}}};"]
    # one brace per group right of the axis, spanning the group's rows
    first = 0
    for group, label in ((ACCOUNT, "Account"), (DERIVED, "Twin")):
        last = first + sum(g == group for g, _ in ROWS) - 1
        L.append(rf"\draw[decorate, decoration={{brace, amplitude=3pt}}] (axis cs:{xmax * 1.03:.1f},{first - 0.35})"
                 rf" -- (axis cs:{xmax * 1.03:.1f},{last + 0.35})"
                 rf" node[midway, right=4pt, rotate=-90, anchor=south, font=\scriptsize] {{{label}}};")
        first = last + 1
    L += [r"\end{axis}",
          r"\end{tikzpicture}"]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True, help="security JSON, e.g. MGridICSA-SecurityEval.json")
    ap.add_argument("--output", default="fig_security.tex")
    a = ap.parse_args()
    open(a.output, "w").write(tex(*count(a.input)))


if __name__ == "__main__":
    main()
